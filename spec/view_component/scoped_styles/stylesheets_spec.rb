# frozen_string_literal: true

require "tmpdir"
require "timeout"

RSpec.describe "Component output stylesheets" do
  before do
    @root = Pathname.new(Dir.mktmpdir("scoped-styles"))
    @config = ViewComponent::ScopedStyles::Configuration.new
    allow(Rails).to receive(:root).and_return(@root)
    allow(ViewComponent::ScopedStyles).to receive(:configuration).and_return(@config)
  end

  after do
    FileUtils.remove_entry(@root)
  end

  def component(name, stylesheet = nil, css = ".component { color: red; }")
    klass = Class.new do
      include ViewComponent::ScopedStyles
    end
    allow(klass).to receive(:name).and_return(name)
    klass.stylesheet(stylesheet) if stylesheet
    klass.styles { css }
    klass
  end

  def output(name)
    @root.join(@config.assets_path, name)
  end

  it "uses the configured default and inherits explicit choices" do
    @config.stylesheet_name = "default.css"
    parent = component("Parent", "admin")
    child = Class.new(parent)
    sibling = Class.new(parent)

    default = component("Default")
    expect(default.stylesheet).to be_nil
    ViewComponent::ScopedStyles::Stylist::Writer.print(default)
    expect(output("default.css").read).to include(default.component_styles)
    expect(child.stylesheet).to eq("admin")
    child.stylesheet("child")
    expect(child.stylesheet).to eq("child")
    expect(parent.stylesheet).to eq("admin")
    expect(sibling.stylesheet).to eq("admin")
  end

  it "groups components by output filename and updates without duplication" do
    first = component("First", "admin")
    second = component("Second", "admin", ".component { color: blue; }")
    default = component("Default")
    writer = ViewComponent::ScopedStyles::Stylist::Writer.new

    [first, second, default, first].each { |klass| writer.print!(klass) }

    shared = output("admin.scoped.css").read
    expect(shared).to include(first.component_styles, second.component_styles)
    expect(shared.scan("/* First */").size).to eq(1)
    expect(shared).not_to include("/* Default */")
    expect(output("components.scoped.css").read).to include("/* Default */")
    expect(output("components.scoped.css").read).not_to include("/* First */", "/* Second */")
  end

  it "keeps all shared components inside a single configured layer" do
    @config.components_layer = "components"
    first = component("First", "admin")
    second = component("Second", "admin")

    [first, second, first].each do |klass|
      ViewComponent::ScopedStyles::Stylist::Writer.print(klass)
    end

    expect(output("admin.scoped.css").read).to eq(
      "/* Generated by ViewComponent::ScopedStyles - Do not edit manually */\n" \
      "@layer components {\n" \
      "/* First */\n#{first.component_styles}/* /First */\n" \
      "/* Second */\n#{second.component_styles}/* /Second */\n}\n"
    )
  end

  it "preserves both components when processes update the same bundle" do
    first = component("First", "shared")
    second = component("Second", "shared", ".component { color: blue; }")
    stylesheet = output("shared.scoped.css")
    FileUtils.mkdir_p(stylesheet.dirname)
    stylesheet.write("/* initial */\n")
    ready_reader, ready_writer = IO.pipe
    release_reader, release_writer = IO.pipe
    done_reader, done_writer = IO.pipe
    children = []

    children << fork do
      allow(File).to receive(:read).and_wrap_original do |read, *args|
        content = read.call(*args)
        if args.first == stylesheet
          ready_writer.write("r")
          release_reader.read(1)
        end
        content
      end
      ViewComponent::ScopedStyles::Stylist::Writer.print(first)
      exit! 0
    end

    Timeout.timeout(5) do
      ready_reader.read(1)
      children << fork do
        ready_writer.write("r")
        ViewComponent::ScopedStyles::Stylist::Writer.print(second)
        done_writer.write("d")
        exit! 0
      end
      ready_reader.read(1)
      IO.select([done_reader], nil, nil, 0.2)
      release_writer.write("r")
      statuses = children.map { Process.wait2(_1).last }
      children.clear
      expect(statuses).to all(be_success)
    end

    expect(stylesheet.read).to include(
      "/* First */", first.component_styles,
      "/* Second */", second.component_styles
    )
  ensure
    children&.each do |pid|
      Process.kill("KILL", pid)
      Process.wait(pid)
    end
    [ready_reader, ready_writer, release_reader, release_writer,
      done_reader, done_writer].compact.each(&:close)
  end

  it "uses the same output selection for sidecar styles" do
    sidecar = @root.join("sidecar.css")
    sidecar.write(".component { display: block; }")
    klass = Class.new do
      include ViewComponent::ScopedStyles
    end
    allow(klass).to receive_messages(name: "Sidecar", sidecar_files: [sidecar.to_s])
    klass.stylesheet("shared")

    ViewComponent::ScopedStyles::Stylist::Writer.print(klass)

    expect(output("shared.scoped.css").read).to include(klass.component_styles)
    expect(output("components.scoped.css")).not_to exist
  end
end
